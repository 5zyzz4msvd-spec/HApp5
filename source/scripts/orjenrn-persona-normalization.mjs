export function normalizeOrjenrnPersonaEntry(entry) {
  if (!entry || typeof entry !== "object") return entry;
  const clone = structuredClone(entry);
  if (String(clone.comment || clone.name || "").trim() !== OTAKU_FEMALE_COMMENT) return clone;
  let content = String(clone.content || "");
  for (const [before, after] of OTAKU_FEMALE_GAME_REALITY_REPLACEMENTS) {
    content = content.replaceAll(before, after);
  }
  clone.content = content;
  return clone;
}
